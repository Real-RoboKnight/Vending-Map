@app.post("/analyse/image/")
async def analyse_image(image: UploadFile) -> list[str]:
    """Analyse an image and return a list of items that are detected in the image.""" 
    b64_image = image.read()

    # get all items in our database to compare with the image
    items_in_db = []
    async for location in locations_collection.find({}, {"items.name": 1}):
        for location_item in location.get("items", []):
            name = location_item.get("name", "")
            if name not in items_in_db:
                items_in_db.append(name)

    # Create a model schema that only lets the model return items that are in our database
    schema = {
        "type": "object",
        "properties": {
            "items": {
                "type": "array",
                "items": {
                    "type": "string",
                    "enum": items_in_db,
                },
            },
        },
        "required": ["items"],
    }

    def minify_image_bytes(
        image_bytes: bytes, quality: int = 50, output_format: str = "JPEG"
        ) -> bytes:
        # Load the raw bytes into a file-like stream
        input_stream = io.BytesIO(image_bytes)
        img = Image.open(input_stream)

        # Convert RGBA/P to RGB if saving as JPEG (JPEG does not support transparency)
        if output_format.upper() == "JPEG" and img.mode in ("RGBA", "P"):
            img = img.convert("RGB")
        img.thumbnail((1024, 1024))  # Resize to a max of 1024px while maintaining aspect ratio

        # Save the compressed image to a new in-memory byte stream
        output_stream = io.BytesIO()
        img.save(output_stream, format=output_format, optimize=True, quality=quality)

        # Return the minified bytes
        return output_stream.getvalue()

    b64_image = base64.b64encode(minify_image_bytes(await b64_image)).decode("utf-8")  # Convert the image to base64 string
    
    gemini_response = gemini.interactions.create(
        model="gemini-3.5-flash",
        input=
        [{"type": "text", "text": f"Analyse the following image and return a list of items detected in it. Return all the items in a JSON array under the key 'items'. Only return items that are in the following list: {items_in_db}."},
         {"type": "image", "data": b64_image, "mime_type": "image/jpeg"}],
        response_format={
            "type": "text",
            "mime_type": "application/json",
            "schema": schema,
        },
    )
    output: str = gemini_response.output_text # type: ignore

    try:
        output = json.loads(output).get("items", [])
    except json.JSONDecodeError as e:
        raise HTTPException(status_code=500, detail="Parsing JSON Error") from e

    return [item for item in output if item in items_in_db]

