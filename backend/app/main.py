class item(BaseModel):
    name: str = Field(default="")
    price: float = Field(default=0.0, ge=0.0)

class machine_location(BaseModel):
    id: PyObjectId | None = Field(alias="_id", default=None)
    name: str | None = Field(default=None)
    longitude: float = Field(default=0.0, ge=-180.0, le=180.0)
    latitude: float = Field(default=0.0, ge=-90.0, le=90.0)
    cash: bool | None = Field(default=None)
    tap: bool | None = Field(default=None)
    mng: bool | None = Field(default=None)
    items: list[item] = Field(default=[])
    
    model_config = ConfigDict(
        validate_by_name=True,
        arbitrary_types_allowed=True,
        json_schema_extra={
            "example": {
                "_id": "6af8ec36812ac87c4f04e0ec",
                "name": "Example Location",
                "longitude": -111.9194,
                "latitude": 33.4749,
                "cash": True,
                "tap": False,
                "mng": False,
                "items": [
                    {
                        "name": "Cheetos Crunchy Flamin' Hot 1.75oz",
                        "price": 1.99,
                    }
                ],
            }
        },
    )

@app.get("/locations/")
async def get_locations(
    min_longitude: float, min_latitude: float, max_longitude: float, max_latitude: float
) -> list[machine_location]:
    """Get all locations within the given bounding box. Will return a list of machine_location objects."""
    locations = []
    async for location in locations_collection.find(
        {
            "longitude": {"$gte": min_longitude, "$lte": max_longitude},
            "latitude": {"$gte": min_latitude, "$lte": max_latitude},
        }
    ):
        locations.append(machine_location.model_validate(location))
    return locations

@app.post("/locations/")
async def create_location(location: machine_location) -> str:
    """Create a NEW location in the database. Will return the ID of the new location if the location was created successfully, empty string otherwise.
    Do not include an ID in the request body, as it will be generated by the database. If an ID is included, it will be ignored.
    """
    if location.id and await locations_collection.find_one({"id": location.id}) is not None:
        return ""

    new_location = location.model_dump(by_alias=True, exclude={"id"})
    result = await locations_collection.insert_one(new_location)
    return str(result.inserted_id)

@app.put("/locations/")
async def update_location(location: machine_location) -> bool:
    """Update an existing location in the database. Will return True if the location was updated successfully, False otherwise.
    Will return False if the location does not exist in the database.
    """
    if location.id is None or not ObjectId.is_valid(location.id):
        return False

    updated_location = location.model_dump(by_alias=True, exclude={"id"})
    result = await locations_collection.find_one_and_update(
        {"_id": ObjectId(location.id)},
        {"$set": updated_location},
        return_document=ReturnDocument.AFTER,
    )

    return result is not None

@app.get("/search/autocomplete/")
async def autocomplete_search(query: str) -> list[str]:
    """Search for items by name. Will return a list of items can be autocompleted."""
    items = []
    try:
        async for item in await locations_collection.aggregate([
            {
                "$search": {
                    "index": "default",
                    "autocomplete": {
                        "path": "items.name",
                        "query": query,
                        "tokenOrder": "any",
                        "fuzzy": {
                            "maxEdits": 2,
                            "prefixLength": 1,
                            "maxExpansions": 256,
                        },
                    },
                }
            },
            {"$unwind": "$items"},
            {"$group": {"_id": "$items.name"}},
            {"$sort": {"_id": 1}},
            {"$limit": 5},
        ]):
            items.append(item["_id"])
    except Exception:
        # Atlas Search is optional while the search index is being configured.
        pass

    if not items:
        async for location in locations_collection.find(
            {"items.name": {"$regex": query, "$options": "i"}},
            {"items.name": 1},
        ):
            for location_item in location.get("items", []):
                name = location_item.get("name", "")
                if query.lower() in name.lower() and name not in items:
                    items.append(name)
                    if len(items) == 5:
                        return sorted(items)

    return items